import { chromium } from 'playwright-core';
const b = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-gl=angle'] });
const p = await b.newPage({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true });
p.on('pageerror', (e) => console.log('ERR', e.message));
await p.goto('http://localhost:4173/', { waitUntil: 'networkidle' });
await p.evaluate(() => localStorage.clear());
await p.reload({ waitUntil: 'networkidle' });
await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/40-m-title.png' });
await p.getByRole('button', { name: /Start Adventure/ }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/41-m-characters.png' });
await p.getByRole('button', { name: /Take me to the island/ }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/42-m-world.png' });
await p.getByRole('button', { name: /Walk into Cartoon/i }).click();
await p.waitForTimeout(1600);
await p.screenshot({ path: 'shots/43-m-intro.png' });
const go = p.getByRole('button', { name: /Let's go/ });
if (await go.isVisible().catch(() => false)) await go.click();
await p.waitForTimeout(600);
await p.screenshot({ path: 'shots/44-m-game.png' });
console.log('state', await p.evaluate(() => window.__cv.state()));
const stick = p.locator('.touch-controls > div').first();
const box = await stick.boundingBox();
console.log('stick box', box);
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
await p.mouse.down();
await p.mouse.move(box.x + box.width / 2 + 40, box.y + box.height / 2, { steps: 4 });
await p.waitForTimeout(900);
await p.mouse.up();
console.log('after joystick', await p.evaluate(() => window.__cv.state()));
const jy0 = (await p.evaluate(() => window.__cv.state())).y;
await p.getByRole('button', { name: /^JUMP/ }).dispatchEvent('pointerdown');
await p.waitForTimeout(170);
const jy1 = (await p.evaluate(() => window.__cv.state())).y;
await p.getByRole('button', { name: /^JUMP/ }).dispatchEvent('pointerup');
console.log('jump', jy0, '->', jy1);
await p.screenshot({ path: 'shots/45-m-controls.png' });
await b.close();
